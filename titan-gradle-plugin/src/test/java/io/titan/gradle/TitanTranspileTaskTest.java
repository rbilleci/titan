    // GAP S8: the task no longer fingerprints its own inputs; when it runs it must regenerate
    // deterministically (unchanged artifacts are left byte-identical and a manually deleted
    // artifact reappears). Skipping reruns is exclusively Gradle's up-to-date check now.
    @Test
    void rerunsAreDeterministicAndRegenerateDeletedArtifacts() throws Exception {
        Project project = ProjectBuilder.builder().build();
        TitanTranspileTask task = project.getTasks().create("titanTranspileFingerprintTest", TitanTranspileTask.class);

        Path sourceDir = tempDir.resolve("src-fingerprint");
        Files.createDirectories(sourceDir.resolve("titan/dsl"));
        Files.createDirectories(sourceDir.resolve("demo"));

        Path annotationSource = sourceDir.resolve("titan/dsl/StoredProcedure.java");
        Files.writeString(annotationSource, """
                package titan.dsl;

                import java.lang.annotation.ElementType;
                import java.lang.annotation.Retention;
                import java.lang.annotation.RetentionPolicy;
                import java.lang.annotation.Target;

                @Retention(RetentionPolicy.RUNTIME)
                @Target(ElementType.METHOD)
                public @interface StoredProcedure {}
                """);

        Path entryPointSource = sourceDir.resolve("demo/EntryPoints.java");
        Files.writeString(entryPointSource, """
                package demo;

                import titan.dsl.StoredProcedure;

                class EntryPoints {
                    @StoredProcedure
                    public static void syncAccounts() {
                    }
                }
                """);

        task.getSourceFiles().from(annotationSource.toFile(), entryPointSource.toFile());
        task.getTargets().set(java.util.List.of("postgresql"));
        task.getOutputDir().set(tempDir.resolve("generated-sql-fingerprint").toFile());

        task.run();

        Path dialectDir = tempDir.resolve("generated-sql-fingerprint/postgresql");
        Path generatedSql = firstSqlFile(dialectDir);
        String firstContent = Files.readString(generatedSql);

        task.run();

        assertEquals(firstContent, Files.readString(generatedSql),
                "reruns over identical inputs must produce byte-identical SQL artifacts");
        assertFalse(Files.exists(tempDir.resolve("generated-sql-fingerprint/.titan-transpile.fingerprint")),
                "homegrown fingerprints are deleted (GAP S8); Gradle owns incrementality");

        Files.delete(generatedSql);
        task.run();

        assertTrue(Files.exists(generatedSql), "a deleted SQL artifact must be regenerated by the next run");
        assertEquals(firstContent, Files.readString(generatedSql));
    }

